#!/usr/bin/env python3
"""Derive, check and publish program progress.

.claude/docs/ROADMAP.md and .claude/docs/LEARNING_LOG.md are written by hand
and are the only source of truth. Everything else about progress is derived
from them:

    progress.py derive           # -> .claude/docs/progress.json
    progress.py check            # validate roadmap <-> log, exit 1 on defects
    progress.py inject           # write the JSON into roadmap.html
    progress.py sync             # check, then derive + inject

progress.json deliberately contains NO value measured from "today" beyond
`generated_at`. Day counts, the current week and slippage are computed in the
browser from `program.start`, so the dashboard cannot go stale between runs —
only the marks can, and `check` is what catches that.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
ROADMAP_MD = ROOT / ".claude" / "docs" / "ROADMAP.md"
LOG_MD = ROOT / ".claude" / "docs" / "LEARNING_LOG.md"
OUT_JSON = ROOT / ".claude" / "docs" / "progress.json"
DASHBOARD = ROOT / "roadmap.html"

BEGIN = "<!-- progress:begin — generated by .claude/scripts/progress.py, do not edit -->"
END = "<!-- progress:end -->"

STATUS_NAME = {" ": "not-started", "~": "progress", "x": "done", "!": "blocked"}

DAY = dt.timedelta(days=1)


# ---------------------------------------------------------------- parsing ---

MARK = r"`\[([ x~!])\]`"

RE_PROGRAM = re.compile(
    r"Program runs \w+ (\d{4}-\d{2}-\d{2}) → (\d{4}-\d{2}-\d{2}): (\d+) weeks, (\d+) days"
)
RE_SCHEDULE_ROW = re.compile(
    r"^\|\s*(\d+)\s*\|\s*(\d{4}-\d{2}-\d{2})\s*\|\s*(\d{4}-\d{2}-\d{2})\s*\|"
    r"\s*(\d+)\s*\|\s*(.+?)\s*\|\s*" + MARK + r"\s*\|\s*$"
)
RE_MONTH_HEAD = re.compile(r"^## Month (\d+) — (.+?)\s*$")
RE_MONTH_STATUS = re.compile(r"^\*\*Status:\*\*\s*" + MARK + r"\s*$")
RE_WEEK = re.compile(
    r"^- " + MARK + r" \*\*Week (\d+)\*\* `(\d{4}-\d{2}-\d{2}) → (\d{4}-\d{2}-\d{2})`"
    r" — (.+?)\s*$"
)
RE_ITEM = re.compile(r"^- " + MARK + r"\s*(.+?)\s*$")
RE_EXIT = re.compile(r"^Exit criteria:\s*" + MARK + r"\s*(.+?)\s*$")
RE_UNPLANNED_ROW = re.compile(
    r"^\|\s*(\d{4}-\d{2}-\d{2})\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*$"
)
RE_SESSION_HEAD = re.compile(r"^## (\d{4}-\d{2}-\d{2}) — (.+?)\s*$")
RE_MATRIX_ROW = re.compile(
    r"^\|\s*(.+?)\s*\|\s*(\d)(?:\s*\(prov\.\))?\s*\|\s*(.+?)\s*\|"
    r"\s*(\d{4}-\d{2}-\d{2})\s*\|\s*(.+?)\s*\|\s*$"
)


def d(s: str) -> dt.date:
    return dt.date.fromisoformat(s)


def strip_md(s: str) -> str:
    """Flatten inline markdown to plain text for the JSON payload."""
    s = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", s)
    s = re.sub(r"\*\*([^*]+)\*\*", r"\1", s)
    s = re.sub(r"`([^`]+)`", r"\1", s)
    return s.strip()


def parse_roadmap(text: str) -> dict:
    lines = text.splitlines()

    m = RE_PROGRAM.search(text)
    if not m:
        raise SystemExit(
            "ROADMAP.md: cannot find the program line "
            "('Program runs <Day> YYYY-MM-DD → YYYY-MM-DD: N weeks, M days')"
        )
    program = {
        "start": m.group(1),
        "end": m.group(2),
        "weeks": int(m.group(3)),
        "days": int(m.group(4)),
    }

    schedule = []
    for line in lines:
        sm = RE_SCHEDULE_ROW.match(line)
        if sm:
            schedule.append(
                {
                    "n": int(sm.group(1)),
                    "start": sm.group(2),
                    "end": sm.group(3),
                    "weeks": int(sm.group(4)),
                    "focus": sm.group(5),
                    "status": sm.group(6),
                }
            )

    # Month sections: weeks, deliverables, exit criterion.
    months: dict[int, dict] = {}
    current: dict | None = None
    section: str | None = None
    for line in lines:
        if line.startswith("## "):
            hm = RE_MONTH_HEAD.match(line)
            current = (
                {
                    "n": int(hm.group(1)),
                    "title": hm.group(2),
                    "status": " ",
                    "weeks": [],
                    "deliverables": [],
                    "exit": None,
                }
                if hm
                else None
            )
            if current:
                months[current["n"]] = current
            section = None
            continue
        if current is None:
            continue

        sm = RE_MONTH_STATUS.match(line)
        if sm:
            current["status"] = sm.group(1)
            continue

        wm = RE_WEEK.match(line)
        if wm:
            current["weeks"].append(
                {
                    "n": int(wm.group(2)),
                    "status": wm.group(1),
                    "start": wm.group(3),
                    "end": wm.group(4),
                    "title": strip_md(wm.group(5)),
                }
            )
            continue

        em = RE_EXIT.match(line)
        if em:
            current["exit"] = {"status": em.group(1), "text": strip_md(em.group(2))}
            section = None
            continue

        if line.strip() == "Deliverables:":
            section = "deliverables"
            continue

        im = RE_ITEM.match(line)
        if section == "deliverables":
            if im:
                current["deliverables"].append(
                    {"status": im.group(1), "text": strip_md(im.group(2))}
                )
            elif line.strip():
                section = None

    # Unplanned work table rows (date in the first cell).
    unplanned = []
    in_unplanned = False
    for line in lines:
        if line.startswith("## Unplanned work"):
            in_unplanned = True
            continue
        if in_unplanned and line.startswith("## "):
            break
        if in_unplanned:
            um = RE_UNPLANNED_ROW.match(line)
            if um:
                unplanned.append(
                    {
                        "date": um.group(1),
                        "work": strip_md(um.group(2)),
                        "artifact": strip_md(um.group(3)),
                        "feeds": strip_md(um.group(4)),
                    }
                )

    # Six-month level targets.
    targets = []
    in_targets = False
    for line in lines:
        if line.startswith("## Six-month level targets"):
            in_targets = True
            continue
        if in_targets and line.startswith("## "):
            break
        if in_targets:
            im = RE_ITEM.match(line)
            if im:
                targets.append({"status": im.group(1), "text": strip_md(im.group(2))})

    return {
        "program": program,
        "schedule": schedule,
        "months": [months[k] for k in sorted(months)],
        "unplanned": unplanned,
        "targets": targets,
    }


def parse_log(text: str) -> dict:
    lines = text.splitlines()

    sessions = []
    for i, line in enumerate(lines):
        sm = RE_SESSION_HEAD.match(line)
        if sm:
            body = "\n".join(lines[i : i + 40])
            artifact = ""
            am = re.search(r"\*\*Output\.\*\*\s*\[([^\]]+)\]\(([^)]+)\)", body)
            if am:
                artifact = am.group(2)
            sessions.append(
                {"date": sm.group(1), "title": sm.group(2), "artifact": artifact}
            )

    matrix = []
    for line in lines:
        mm = RE_MATRIX_ROW.match(line)
        if mm and mm.group(1) != "Topic":
            matrix.append(
                {
                    "topic": strip_md(mm.group(1)),
                    "level": int(mm.group(2)),
                    "provisional": "(prov.)" in line,
                    "evidence": strip_md(mm.group(3)),
                    "date": mm.group(4),
                }
            )

    return {"sessions": sessions, "matrix": matrix}


# ----------------------------------------------------------------- derive ---


def derive(roadmap: dict, log: dict) -> dict:
    months = []
    deliv_done = deliv_total = 0
    for mo in roadmap["months"]:
        sched = next((s for s in roadmap["schedule"] if s["n"] == mo["n"]), None)
        dd = sum(1 for x in mo["deliverables"] if x["status"] == "x")
        deliv_done += dd
        deliv_total += len(mo["deliverables"])
        months.append(
            {
                "n": mo["n"],
                "title": mo["title"],
                "status": mo["status"],
                "start": sched["start"] if sched else None,
                "end": sched["end"] if sched else None,
                "weeks_planned": sched["weeks"] if sched else len(mo["weeks"]),
                "weeks": mo["weeks"],
                "deliverables": mo["deliverables"],
                "deliverables_done": dd,
                "exit": mo["exit"],
            }
        )

    levels: dict[str, int] = {}
    for row in log["matrix"]:
        levels[str(row["level"])] = levels.get(str(row["level"]), 0) + 1

    sessions = []
    unplanned_dates = {u["date"] for u in roadmap["unplanned"]}
    for s in log["sessions"]:
        feeds = next(
            (u["feeds"] for u in roadmap["unplanned"] if u["date"] == s["date"]), ""
        )
        sessions.append({**s, "planned": s["date"] not in unplanned_dates, "feeds": feeds})
    sessions.sort(key=lambda s: s["date"], reverse=True)

    return {
        "generated_at": dt.date.today().isoformat(),
        "program": roadmap["program"],
        "months": months,
        "deliverables": {"done": deliv_done, "total": deliv_total},
        "sessions": sessions,
        "unplanned": roadmap["unplanned"],
        "targets": {
            "done": sum(1 for t in roadmap["targets"] if t["status"] == "x"),
            "total": len(roadmap["targets"]),
            "items": roadmap["targets"],
        },
        "competency": {"rows": log["matrix"], "levels": levels},
    }


# ------------------------------------------------------------------ check ---


def check(
    roadmap: dict, log: dict, data: dict, today: dt.date
) -> tuple[list[str], list[str]]:
    """Return (content defects, dashboard-staleness defects).

    The two are separated because `sync` repairs staleness by injecting, so it
    must not refuse to run on account of it — while `check` still fails on it,
    which is what stops a stale roadmap.html reaching a commit.
    """
    defects: list[str] = []
    program = roadmap["program"]
    start, end = d(program["start"]), d(program["end"])
    sched = roadmap["schedule"]
    session_dates = {s["date"] for s in log["sessions"]}

    # --- 1. the schedule has to be internally consistent -------------------
    if (end - start).days + 1 != program["days"]:
        defects.append(
            f"schedule: program line says {program['days']} days but "
            f"{program['start']}→{program['end']} spans {(end - start).days + 1}"
        )
    if sum(s["weeks"] for s in sched) != program["weeks"]:
        defects.append(
            f"schedule: month weeks sum to {sum(s['weeks'] for s in sched)}, "
            f"program line says {program['weeks']}"
        )
    for a, b in zip(sched, sched[1:]):
        if d(b["start"]) != d(a["end"]) + DAY:
            defects.append(
                f"schedule: month {a['n']} ends {a['end']} but month {b['n']} "
                f"starts {b['start']} — months must be contiguous"
            )
    for s in sched:
        span = (d(s["end"]) - d(s["start"])).days + 1
        if span != s["weeks"] * 7:
            defects.append(
                f"schedule: month {s['n']} spans {span} days but claims "
                f"{s['weeks']} weeks ({s['weeks'] * 7} days)"
            )
    if sched and sched[0]["start"] != program["start"]:
        defects.append(
            f"schedule: month 1 starts {sched[0]['start']}, program starts {program['start']}"
        )
    if sched and sched[-1]["end"] != program["end"]:
        defects.append(
            f"schedule: month {sched[-1]['n']} ends {sched[-1]['end']}, "
            f"program ends {program['end']}"
        )

    # --- 2. month status in the table must match the month section ---------
    for s in sched:
        mo = next((m for m in roadmap["months"] if m["n"] == s["n"]), None)
        if mo is None:
            defects.append(f"schedule: month {s['n']} has no '## Month {s['n']}' section")
        elif mo["status"] != s["status"]:
            defects.append(
                f"month {s['n']}: schedule table says [{s['status']}] but the "
                f"section says [{mo['status']}] — they must agree"
            )

    # --- 3. weeks must tile their month, in order --------------------------
    for mo in roadmap["months"]:
        s = next((x for x in sched if x["n"] == mo["n"]), None)
        if not mo["weeks"] or s is None:
            continue
        if len(mo["weeks"]) != s["weeks"]:
            defects.append(
                f"month {mo['n']}: {len(mo['weeks'])} week lines but the schedule "
                f"says {s['weeks']} weeks"
            )
        for w in mo["weeks"]:
            if (d(w["end"]) - d(w["start"])).days != 6:
                defects.append(
                    f"month {mo['n']} week {w['n']}: {w['start']}→{w['end']} is not 7 days"
                )
        for a, b in zip(mo["weeks"], mo["weeks"][1:]):
            if d(b["start"]) != d(a["end"]) + DAY:
                defects.append(
                    f"month {mo['n']}: week {a['n']} ends {a['end']} but week "
                    f"{b['n']} starts {b['start']} — weeks must be contiguous"
                )
        if d(mo["weeks"][0]["start"]) != d(s["start"]):
            defects.append(
                f"month {mo['n']}: week 1 starts {mo['weeks'][0]['start']}, "
                f"month starts {s['start']}"
            )

    # --- 4. nothing may be marked done in the future -----------------------
    for mo in roadmap["months"]:
        for w in mo["weeks"]:
            if w["status"] == "x" and d(w["start"]) > today:
                defects.append(
                    f"month {mo['n']} week {w['n']}: marked [x] but it does not "
                    f"start until {w['start']} (today is {today})"
                )
    for s in log["sessions"]:
        if d(s["date"]) > today:
            defects.append(f"log: session '{s['title']}' is dated {s['date']}, in the future")

    # --- 5. [x] requires evidence in the log -------------------------------
    for mo in roadmap["months"]:
        sch = next((x for x in sched if x["n"] == mo["n"]), None)
        if sch is None:
            continue
        lo, hi = d(sch["start"]), d(sch["end"])
        in_month = [x for x in session_dates if lo <= d(x) <= hi]
        feeds_month = [
            u for u in roadmap["unplanned"] if re.search(rf"Month {mo['n']}\b", u["feeds"])
        ]
        marked = [w for w in mo["weeks"] if w["status"] == "x"]
        marked += [x for x in mo["deliverables"] if x["status"] == "x"]
        if mo["exit"] and mo["exit"]["status"] == "x":
            marked.append(mo["exit"])
        # Count evidence rather than merely requiring some: one old unplanned row
        # must not excuse every [x] the month will ever collect.
        evidence = len(set(in_month) | {u["date"] for u in feeds_month})
        if len(marked) > evidence:
            defects.append(
                f"month {mo['n']}: {len(marked)} item(s) marked [x] but only "
                f"{evidence} session(s) behind them in LEARNING_LOG.md "
                f"(dated {sch['start']}..{sch['end']}, or an Unplanned work row "
                f"feeding Month {mo['n']}) — [x] requires evidence"
            )

    # --- 6. every session is accounted for on the roadmap ------------------
    for s in log["sessions"]:
        sd = d(s["date"])
        on_plan = any(
            d(x["start"]) <= sd <= d(x["end"]) and x["status"] in "~x" for x in sched
        )
        if s["date"] not in {u["date"] for u in roadmap["unplanned"]} and not on_plan:
            defects.append(
                f"log: session {s['date']} '{s['title']}' is neither inside an active "
                f"month nor listed in the Unplanned work table of ROADMAP.md"
            )

    # --- 7. unplanned rows must have a session behind them -----------------
    for u in roadmap["unplanned"]:
        if u["date"] not in session_dates:
            defects.append(
                f"roadmap: Unplanned work row dated {u['date']} has no "
                f"LEARNING_LOG.md session on that date"
            )

    # --- 8. competency rows must cite a real session -----------------------
    for row in log["matrix"]:
        if row["date"] not in session_dates:
            defects.append(
                f"log: competency row '{row['topic'][:40]}' is dated {row['date']}, "
                f"which is not the date of any session"
            )
        if row["level"] >= 3 and row["provisional"] is False:
            # Level 3+ needs evidence beyond notes; we can only flag it for review.
            defects.append(
                f"log: competency row '{row['topic'][:40]}' claims Level {row['level']} "
                f"without '(prov.)' — Level 3+ needs a measurement, an experiment or "
                f"real code behind it (TECHNICAL_GROWTH.md §10)"
            )

    # --- 9. silent slippage: the calendar moved, the marks did not ---------
    if start <= today <= end:
        elapsed_week = (today - start).days // 7 + 1
        cal_month = next((s for s in sched if d(s["start"]) <= today <= d(s["end"])), None)
        if cal_month and cal_month["status"] == " ":
            defects.append(
                f"slippage: today is {today}, inside month {cal_month['n']} "
                f"({cal_month['start']}..{cal_month['end']}), but that month is still "
                f"[ ]. Mark it [~], or [!] with a reason."
            )
        if cal_month:
            mo = next((m for m in roadmap["months"] if m["n"] == cal_month["n"]), None)
            if mo and mo["weeks"]:
                cur = next(
                    (w for w in mo["weeks"] if d(w["start"]) <= today <= d(w["end"])), None
                )
                touched = [w for w in mo["weeks"] if w["status"] in "~x!"]
                last = max((w["n"] for w in touched), default=0)
                if cur and cur["n"] - last > 1:
                    defects.append(
                        f"slippage: calendar is in month {mo['n']} week {cur['n']} "
                        f"({cur['start']}..{cur['end']}) but the last week touched is "
                        f"week {last or 'none'} — "
                        f"{cur['n'] - last - 1} week(s) passed unmarked. Mark them [!] "
                        f"with a reason, or move the dates (ROADMAP.md rule 3)."
                    )
        gap = (today - max((d(s["date"]) for s in log["sessions"]), default=start)).days
        if gap > 14:
            defects.append(
                f"log: {gap} days since the last session entry "
                f"({max(s['date'] for s in log['sessions'])}) — the log has gone quiet"
            )
    elif today < start:
        marked = [s for s in sched if s["status"] != " "]
        if marked:
            defects.append(
                f"schedule: month(s) {[s['n'] for s in marked]} are marked but the "
                f"program does not start until {program['start']}"
            )

    # --- 10. the dashboard must be in step with the markdown ---------------
    stale: list[str] = []
    if DASHBOARD.exists():
        html = DASHBOARD.read_text(encoding="utf-8")
        if BEGIN not in html:
            stale.append(
                f"{DASHBOARD.name}: no progress:begin marker — run `progress.py inject`"
            )
        else:
            embedded = extract_injected(html)
            if embedded is None:
                stale.append(f"{DASHBOARD.name}: injected block is not valid JSON")
            else:
                fresh = {k: v for k, v in data.items() if k != "generated_at"}
                old = {k: v for k, v in embedded.items() if k != "generated_at"}
                if fresh != old:
                    stale.append(
                        f"{DASHBOARD.name}: embedded progress data no longer matches "
                        f"ROADMAP.md / LEARNING_LOG.md — run `progress.py sync`"
                    )

    return defects, stale


# ----------------------------------------------------------------- inject ---


def extract_injected(html: str) -> dict | None:
    m = re.search(
        re.escape(BEGIN) + r".*?<script id=\"progress-data\" type=\"application/json\">"
        r"(.*?)</script>.*?" + re.escape(END),
        html,
        re.S,
    )
    if not m:
        return None
    try:
        return json.loads(m.group(1))
    except json.JSONDecodeError:
        return None


def inject(data: dict) -> bool:
    html = DASHBOARD.read_text(encoding="utf-8")
    if BEGIN not in html or END not in html:
        raise SystemExit(
            f"{DASHBOARD.name}: markers not found. Add this inside <body>:\n"
            f"  {BEGIN}\n  <script id=\"progress-data\" type=\"application/json\">"
            f"{{}}</script>\n  {END}"
        )
    payload = json.dumps(data, ensure_ascii=False, indent=2)
    block = (
        BEGIN
        + '\n<script id="progress-data" type="application/json">\n'
        + payload
        + "\n</script>\n"
        + END
    )
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, html, flags=re.S)
    if new == html:
        return False
    DASHBOARD.write_text(new, encoding="utf-8")
    return True


# ------------------------------------------------------------------- main ---


def load() -> tuple[dict, dict, dict]:
    roadmap = parse_roadmap(ROADMAP_MD.read_text(encoding="utf-8"))
    log = parse_log(LOG_MD.read_text(encoding="utf-8"))
    return roadmap, log, derive(roadmap, log)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("command", choices=["derive", "check", "inject", "sync"])
    ap.add_argument("--today", help="override today's date (YYYY-MM-DD), for testing")
    args = ap.parse_args(argv)

    today = d(args.today) if args.today else dt.date.today()
    roadmap, log, data = load()

    if args.command in ("check", "sync"):
        defects, stale = check(roadmap, log, data, today)
        # `sync` is the repair for staleness, so it only blocks on content defects.
        blocking = defects if args.command == "sync" else defects + stale
        if blocking:
            print(f"✗ {len(blocking)} defect(s) — as of {today}\n", file=sys.stderr)
            for x in blocking:
                print(f"  · {x}", file=sys.stderr)
            print(file=sys.stderr)
            if args.command == "sync":
                print("sync: not publishing while defects stand", file=sys.stderr)
            return 1
        print(f"✓ roadmap and log agree — as of {today}")

    if args.command in ("derive", "sync"):
        OUT_JSON.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        print(f"✓ wrote {OUT_JSON.relative_to(ROOT)}")

    if args.command in ("inject", "sync"):
        changed = inject(data)
        print(
            f"✓ {'updated' if changed else 'already current:'} "
            f"{DASHBOARD.relative_to(ROOT)}"
        )

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
